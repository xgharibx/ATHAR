def norm_all(items):
    return [corpus.norm(i["text"]) for i in items]


def is_dup(new_text, existing_norms):
    n = corpus.norm(new_text)
    return any(n in e or e in n for e in existing_norms if len(e) > 8)


def build_item(text, source, benefit="", label=""):
    return {
        "text": text,
        "benefit": benefit,
        "source": source,
        "source_label": label,
        "count": 1,
        "count_description": "مرة واحدة",
    }


def main():
    db = json.load(open(ADHKAR, encoding="utf8"))
    secs = {s["id"]: s for s in db["sections"]}
    report = []

    def add(section_id, item, tag):
        sec = secs[section_id]
        if is_dup(item["text"], norm_all(sec["content"])):
            report.append((section_id, "dup", tag))
            return False
        sec["content"].append(item)
        report.append((section_id, "added", tag + " | " + item["source"]))
        return True

    # Quran duas, split between the prophets' section and the general one.
    for su, ayahs, s, e, who in QURAN:
        text = corpus.find_quran([(su, a) for a in ayahs], s, e)
        if not text:
            report.append(("quran", "MISSING", f"{su}:{ayahs} {s}"))
            continue
        ref = ref_label(su, ayahs)
        if who and any(w in who for w in PROPHETS_WHO) and who not in ("فرعون",):
            add("prophets_duas", build_item(text, f"دعاء {who} ({ref})"), ref)
        else:
            add("quranic_duas", build_item(text, "", benefit=ref), ref)

    for section_id, specs in (("prophetic_duas", PROPHETIC), ("jawami_dua", JAWAMI)):
        for s, e, benefit in specs:
            hit = pick_hadith(s, e)
            if not hit:
                report.append((section_id, "MISSING", s))
                continue
            book, h, piece = hit
            if len(piece) > 420:
                report.append((section_id, "LONG", f"{len(piece)} {s}"))
            src = f"رواه {NOM[book]} ({digits(h['a'])})"
            label = f"{src} — {grade_word(book, h.get('g', []))}"
            add(section_id, build_item(piece, src, benefit, label), s)

    for r in report:
        print(*r, sep=" | ")
    added = sum(1 for r in report if r[1] == "added")
    print(f"\n{added} added, {sum(1 for r in report if r[1] == 'dup')} already present, "
          f"{sum(1 for r in report if r[1] in ('MISSING', 'LONG'))} need attention")
    for k in ("quranic_duas", "prophets_duas", "prophetic_duas", "jawami_dua"):
        print(k, len(secs[k]["content"]))
    if not DRY:
        json.dump(db, open(ADHKAR, "w", encoding="utf8"), ensure_ascii=False, indent=2)
        print("written")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf8")
    main()
