def digits(n):
    return str(n).split(".")[0].translate(AR_DIGITS)


def ref_label(su, ayahs):
    a = ayahs[0] if len(ayahs) == 1 else f"{ayahs[0]}-{ayahs[-1]}"
    return f"{SURAH[su].replace('_', ' ')}: {digits(a)}"


def grade_ok(book, g):
    if book in ("bukhari", "muslim", "malik"):
        return True
    good = sum(1 for x in g if x in ("sahih", "hasan"))
    bad = sum(1 for x in g if x == "daif")
    return good > bad


def grade_word(book, g):
    if book in ("bukhari", "muslim"):
        return "صحيح"
    return "صحيح" if sum(1 for x in g if x == "sahih") >= max(1, len(g) // 2 + (len(g) % 2)) else "حسن"


def cite(book, h):
    return f"{corpus.BOOK_LABEL[book]} ({digits(h['a'])})"


def pick_hadith(start, end=None, books=None):
    for b in (books or corpus.BOOKS):
        for h in corpus.hadiths(b):
            t = h.get("t")
            if not t:
                continue
            piece = corpus.cut(t, start, end)
            if piece and "�" not in piece and grade_ok(b, h.get("g", [])):
                return b, h, piece
    return None


