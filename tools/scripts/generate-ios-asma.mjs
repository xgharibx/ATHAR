/**
 * Writes ios/App/AtharWidgets/AsmaAlHusna.swift from src/data/asmaAlHusna.ts,
 * so the iPhone "Name of the day" widget shows exactly the app's names and
 * meanings. tests/iosAsmaWidget.test.ts fails if the two drift apart.
 *
 *   node tools/scripts/generate-ios-asma.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export function readAsma() {
  const source = fs.readFileSync(path.join(root, "src/data/asmaAlHusna.ts"), "utf8");
  const items = [...source.matchAll(/\{\s*id:\s*(\d+),\s*arabic:\s*"([^"]+)",[^}]*?meaning:\s*"([^"]+)"/g)]
    .map((m) => ({ id: Number(m[1]), arabic: m[2], meaning: m[3] }));
  if (items.length !== 99 || items.some((item, index) => item.id !== index + 1)) {
    throw new Error(`expected names 1..99 in order, found ${items.length}`);
  }
  return items;
}

const swiftString = (text) => `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

export function renderSwift(items) {
  const rows = items.map((item) => `    (${swiftString(item.arabic)}, ${swiftString(item.meaning)}),`).join("\n");
  return `// Generated by tools/scripts/generate-ios-asma.mjs from src/data/asmaAlHusna.ts.
// Do not edit by hand: run the script after changing the app's names.

import Foundation

/// The 99 Names in the app's order: index 0 is name 1.
let asmaAlHusna: [(arabic: String, meaning: String)] = [
${rows}
]

/// Today's Name, by the same rotation as the app and the Android widget:
/// whole UTC days since 1970, mod 99.
func dailyAsmaIndex(at date: Date = Date()) -> Int {
    let days = Int((date.timeIntervalSince1970 / 86_400).rounded(.down))
    return ((days % 99) + 99) % 99
}

/// When today's Name changes (the next UTC midnight).
func nextAsmaChange(after date: Date = Date()) -> Date {
    let days = (date.timeIntervalSince1970 / 86_400).rounded(.down)
    return Date(timeIntervalSince1970: (days + 1) * 86_400)
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = path.join(root, "ios/App/AtharWidgets/AsmaAlHusna.swift");
  fs.writeFileSync(out, renderSwift(readAsma()));
  console.log(`wrote ${path.relative(root, out)}`);
}
