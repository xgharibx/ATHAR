"""
Write src/data/classicalWisdom.ts from the extracted passages (extract_wisdom.py).

    python tools/scripts/emit_wisdom_ts.py <wisdom.json> src/data/classicalWisdom.ts

Keeps the reflective books (Sayd al-Khatir, Kitab al-Fawa'id) and leaves out
passages about disputed theology, politics, or marriage, which do not belong on a
daily card. Run extract_wisdom.py first.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import corpus  # noqa: E402

KEEP = ("صيد الخاطر", "كتاب الفوائد")
AVOID = re.compile(
    r"(علم الكلام|التشبيه|العرش|الحنابل|الشافعي|مذهب|النكاح|المنكح|السلاطين|السلطان|الواعظ|الوعظ|المقرئ|المحدثين"
    r"|القصاص|الرافض|الروافض|أبو بكر|عمر|علي|المرأة|الزوجة|زوجة|الجنس|الجماع|الغناء|الألحان|حنبل|أحمد|لمة)"
)
BADSTART = re.compile(
    r"^(الأول|الأولى|الثاني|الثانية|الثالث|الثالثة|الرابع|الرابعة|الخامس|السادس|السابع|الثامن|التاسع|العاشر|أحدهما|إحداهما"
    r"|والثاني|قلت|فإن قيل|فقد|فلا|فهذا|وهذا|هذا|وهذه|فهذه|الدرجة|الموضع|المقام|الباب|القسم|النوع|الفصل|الوجه|السبب|الفائدة|فائدة|مسألة|تنبيه)"
)
TECH = re.compile(
    r"(الجمع|الفناء|الدرجة|المقام|الموضع|الباب|أرباب|السالك|السلوك|الشهود|شهود|الاتحاد|الحلول|الوحدة|الجبرية|القدرية|المعتزلة"
    r"|الأشعري|الفلاسفة|المتكلم|الخاصة|التفرقة|الباطن|الظاهر|الرسوم|الوجود)"
)


def esc(s):
    return s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def main():
    src = json.loads(Path(sys.argv[1]).read_text(encoding="utf8"))
    out, seen = [], set()
    for x in src:
        if not any(k in x["source"] for k in KEEP):
            continue
        plain = corpus._TASHKEEL.sub("", x["text"])
        if not (120 <= len(plain) <= 340) or BADSTART.match(plain.strip()) or TECH.search(plain) or AVOID.search(plain):
            continue
        if plain.count("،") + plain.count(",") < 1:
            continue
        key = corpus.norm(plain)[:45]
        if key in seen:
            continue
        seen.add(key)
        text = re.sub(r"\s+([،.؟!:؛])", r"\1", x["text"]).strip()
        out.append({"text": text, "source": x["source"]})
    head = (
        "/**\n * Passages from classical books of reflection (Ibn al-Qayyim, Ibn al-Jawzi), taken whole and\n"
        " * unchanged from the open texts on Arabic Wikisource (CC BY-SA 4.0). Generated by\n"
        " * tools/scripts/fetch_wikisource.py, extract_wisdom.py and emit_wisdom_ts.py; each is a\n"
        " * self-contained paragraph or run of sentences that reads on its own. Nothing is paraphrased.\n */\n"
        'import type { Wisdom } from "@/data/dailyWisdom";\n\nexport const CLASSICAL_WISDOMS: Wisdom[] = [\n'
    )
    body = "".join('  {\n    text: `%s`,\n    source: "%s",\n  },\n' % (esc(o["text"]), o["source"]) for o in out)
    Path(sys.argv[2]).write_text(head + body + "];\n", encoding="utf8", newline="\n")
    print(len(out), Counter(o["source"] for o in out))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf8")
    main()
