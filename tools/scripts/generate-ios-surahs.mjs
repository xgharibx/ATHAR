/**
 * Writes ios/App/App/SurahNames.swift from public/data/quran.json, so Siri
 * and Shortcuts know the 114 surahs by the same names the app shows.
 * tests/siriShortcuts.test.ts fails if the two drift apart.
 *
 *   node tools/scripts/generate-ios-surahs.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

/** «سُورَةُ الكَهۡفِ» → «الكهف»: no diacritics or Quranic marks, no «سورة». */
export function plainSurahName(name) {
  return name
    .replace(/آ/g, "آ")
    .replace(/ٱ/g, "ا")
    .replace(/[ؐ-ًؚ-ٰٟۖ-ۭـ]/g, "")
    .replace(/^\s*سورة\s+/, "")
    .replace(/\s+/g, " ")
    .trim();
}

export function readSurahs() {
  const quran = JSON.parse(fs.readFileSync(path.join(root, "public/data/quran.json"), "utf8"));
  const surahs = quran.surahs.map((surah) => ({ id: surah.id, arabic: plainSurahName(surah.name), english: surah.englishName }));
  if (surahs.length !== 114 || surahs.some((surah, index) => surah.id !== index + 1)) {
    throw new Error(`expected surahs 1..114 in order, found ${surahs.length}`);
  }
  return surahs;
}

const swiftString = (text) => `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

export function renderSwift(surahs) {
  const rows = surahs.map((surah) => `        (${swiftString(surah.arabic)}, ${swiftString(surah.english)}),`).join("\n");
  return `// Generated by tools/scripts/generate-ios-surahs.mjs from public/data/quran.json.
// Do not edit by hand: run the script after changing the surah names.

/// The 114 surahs in order: Arabic name without «سورة», and English name.
enum SurahNames {
    static let all: [(arabic: String, english: String)] = [
${rows}
    ]
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "ios/App/App/SurahNames.swift"), renderSwift(readSurahs()));
  console.log("wrote ios/App/App/SurahNames.swift");
}
